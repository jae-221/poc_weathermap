import type { WeatherPoint } from '../types/weatherMap.types'

type OpenMeteoSnapshotPoint = WeatherPoint & {
  cloudCover: number
  name: string
  precipitation: number
}

function toHeatmapWeight(precipitation: number, cloudCover: number) {
  const precipitationScore = Math.min(precipitation / 1.2, 1) * 0.72
  const cloudScore = (cloudCover / 100) * 0.28

  return Number(Math.min(1, precipitationScore + cloudScore).toFixed(2))
}

